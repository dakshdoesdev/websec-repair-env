"""
Generate full trajectory logs from the WebSec environment.

This script runs episodes and logs complete observation/action/reward data
for use in fine-tuning. Much more detailed than metrics.json.

Usage:
    python training/generate_trajectories.py --episodes 50 --output trajectory_logs.json
"""

import json
import argparse
from pathlib import Path
from typing import Any, Dict, List
import sys
import time

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

try:
    from ..models import WebSecRepairAction
    from ..server.challenge import BASELINES, TASKS
    from ..server.websec_repair_environment import WebSecRepairEnvironment
except ImportError:
    from models import WebSecRepairAction  # type: ignore
    from server.challenge import BASELINES, TASKS  # type: ignore
    from server.websec_repair_environment import WebSecRepairEnvironment  # type: ignore


def generate_synthetic_trajectories(num_episodes: int = 50) -> List[Dict[str, Any]]:
    """
    Generate environment-aligned reference trajectories.

    These trajectories are generated by stepping the real environment with the
    public baseline actions, so the recorded next-action supervision matches the
    live reward function and state machine.
    """

    env = WebSecRepairEnvironment()
    task_ids = list(BASELINES.keys())
    trajectories: list[dict[str, Any]] = []

    for ep_num in range(num_episodes):
        task_id = task_ids[ep_num % len(task_ids)]
        baseline = BASELINES[task_id]
        task_config = TASKS[task_id]
        env.reset(task_id=task_id, episode_id=f"ep_{ep_num:03d}")

        trajectory = {
            "episode_id": f"ep_{ep_num:03d}",
            "task_id": task_id,
            "vulnerability_type": task_config["correct_vulnerability"],
            "steps": [],
            "success": False,
            "cumulative_reward": 0.0,
        }

        final_observation = None
        for step_index, baseline_action in enumerate(baseline.actions, start=1):
            action = WebSecRepairAction(
                action_type=baseline_action.action_type,
                vulnerability_type=baseline_action.vulnerability_type,
                patch_id=baseline_action.patch_id,
            )
            final_observation = env.step(action)
            action_input = {}
            if baseline_action.vulnerability_type:
                action_input["vulnerability_type"] = baseline_action.vulnerability_type
            if baseline_action.patch_id:
                action_input["patch_id"] = baseline_action.patch_id

            trajectory["steps"].append(
                {
                    "step": step_index,
                    "action_type": baseline_action.action_type,
                    "action_input": action_input or None,
                    "observation": final_observation.status_message,
                    "reward": float(final_observation.reward or 0.0),
                    "done": final_observation.done,
                    "metadata": final_observation.metadata,
                }
            )

        trajectory["success"] = bool(final_observation and final_observation.grader_passed)
        trajectory["cumulative_reward"] = float(env.state.score)
        trajectories.append(trajectory)

    return trajectories


def generate_from_real_environment(num_episodes: int = 50) -> List[Dict[str, Any]]:
    """
    Generate trajectories from the actual in-process environment.

    The synthetic/reference path already uses the real environment and baseline
    actions, so this is now just an alias for the same implementation.
    """
    print("✅ Using in-process environment baselines for trajectory generation...")
    return generate_synthetic_trajectories(num_episodes)


def main():
    parser = argparse.ArgumentParser(
        description="Generate trajectory logs from WebSec environment"
    )
    parser.add_argument(
        "--episodes",
        type=int,
        default=50,
        help="Number of episodes to generate (default: 50)",
    )
    parser.add_argument(
        "--output",
        type=str,
        default="trajectory_logs.json",
        help="Output file path (default: trajectory_logs.json)",
    )
    parser.add_argument(
        "--synthetic-only",
        action="store_true",
        help="Use only synthetic data (don't try real environment)",
    )
    
    args = parser.parse_args()
    
    print(f"\n{'='*70}")
    print(f"Generating {args.episodes} trajectory logs...")
    print(f"Output: {args.output}")
    print(f"{'='*70}\n")
    
    start_time = time.time()
    
    if args.synthetic_only:
        trajectories = generate_synthetic_trajectories(args.episodes)
    else:
        trajectories = generate_from_real_environment(args.episodes)
    
    # Save to file
    output_path = Path(args.output)
    with open(output_path, "w") as f:
        json.dump({
            "trajectories": trajectories,
            "num_episodes": len(trajectories),
            "generated_at": time.time(),
        }, f, indent=2)
    
    elapsed = time.time() - start_time
    
    print(f"\n{'='*70}")
    print(f"✅ Generated {len(trajectories)} trajectory logs")
    print(f"📁 Saved to: {output_path.absolute()}")
    print(f"⏱️  Time: {elapsed:.1f}s")
    print(f"📊 Total steps: {sum(len(t['steps']) for t in trajectories)}")
    print(f"{'='*70}\n")


if __name__ == "__main__":
    main()
